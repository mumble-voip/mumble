import json
import argparse


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dep-file",
        help="Path to the JSON file containing the dependency meta-information",
        metavar="PATH",
        required=True,
    )
    parser.add_argument(
        "--mumble-license-file",
        help="File containing Mumble's own license text",
        metavar="PATH",
        required=True,
    )
    parser.add_argument(
        "--output",
        help="Path to the file to which the generated code shall be written."
        + " If none is given, the content is written to stdout",
        metavar="PATH",
    )

    args = parser.parse_args()

    content = """/*
 * This file was auto-generated by scripts/generate_license_header.py\n
 * DO NOT EDIT IT MANUALLY
 */
#ifndef MUMBLE_LICENSES_H_
#define MUMBLE_LICENSES_H_

#include <array>
#include <string>
#include <string_view>

struct ThirdPartyLicense {
    std::string name;
    std::string url;
    bool        urlIsSourceCode = false;
    std::string spdxLicenseId;
};


"""

    mumble_license = (
        '\t"'
        + open(args.mumble_license_file, "r")
        .read()
        .strip()
        .replace('"', '\\"')
        .replace("\n", '\\n"\n\t"')
        + '"'
    )
    content += (
        "static constexpr std::string_view mumbleLicense = \n"
        + mumble_license
        + ";\n\n\n"
    )

    content += "static const std::array licenses3rdParties = {\n"

    dep_spec = json.load(open(args.dep_file, "r"))
    dep_spec = dep_spec["dependencies"]

    for current_dep in dep_spec:
        name = current_dep["name"]
        license = current_dep["license"]

        if "website" in current_dep:
            url = current_dep["website"]
            url_is_source = False
        elif "source_code" in current_dep:
            url = current_dep["source_code"]
            url_is_source = True
        else:
            raise RuntimeError(f"No URL for dependency {name}")

        content += f'\tThirdPartyLicense{{.name="{name}", .url="{url}", .urlIsSourceCode={"true" if url_is_source else "false"}, .spdxLicenseId="{license}"}},\n'

    content += "};\n\n"
    content += "#endif // MUMBLE_LICENSES_H_\n"

    if args.output:
        with open(args.output, "w") as outFile:
            outFile.write(content)
    else:
        print(content)


if __name__ == "__main__":
    main()
